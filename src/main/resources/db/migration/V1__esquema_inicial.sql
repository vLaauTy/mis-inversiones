-- Etapa 1: cartera, bolsitas, plazos fijos, precios manuales y plan.
-- Montos en pesos con 4 decimales; tasas guardadas como fracción (0.22 = 22%).

CREATE TABLE activo (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker       VARCHAR(20)  NOT NULL UNIQUE,
    nombre       VARCHAR(120) NOT NULL,
    tipo         VARCHAR(20)  NOT NULL,
    nivel_riesgo VARCHAR(10)  NOT NULL
);

CREATE TABLE operacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha           DATE           NOT NULL,
    activo_id       BIGINT         NOT NULL REFERENCES activo (id),
    tipo            VARCHAR(10)    NOT NULL,
    cantidad        NUMERIC(19, 6) NOT NULL,
    precio_unitario NUMERIC(19, 4) NOT NULL,
    comision        NUMERIC(19, 4) NOT NULL,
    origen          VARCHAR(10)    NOT NULL,
    nota            VARCHAR(255),
    creada_en       TIMESTAMP      NOT NULL
);
CREATE INDEX idx_operacion_activo ON operacion (activo_id, fecha);

CREATE TABLE precio (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo_id  BIGINT         NOT NULL REFERENCES activo (id),
    fecha_hora TIMESTAMP      NOT NULL,
    precio_ars NUMERIC(19, 4) NOT NULL,
    fuente     VARCHAR(10)    NOT NULL
);
CREATE INDEX idx_precio_activo_fecha ON precio (activo_id, fecha_hora);

CREATE TABLE bolsita (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(80)    NOT NULL UNIQUE,
    tipo      VARCHAR(20)    NOT NULL,
    entidad   VARCHAR(80),
    tasa      NUMERIC(9, 6),
    meta      NUMERIC(19, 4),
    fecha_uso DATE
);

CREATE TABLE movimiento_bolsita (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolsita_id BIGINT         NOT NULL REFERENCES bolsita (id),
    fecha      DATE           NOT NULL,
    tipo       VARCHAR(10)    NOT NULL,
    monto      NUMERIC(19, 4) NOT NULL,
    nota       VARCHAR(255)
);
CREATE INDEX idx_movimiento_bolsita ON movimiento_bolsita (bolsita_id, fecha);

CREATE TABLE plazo_fijo (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolsita_id        BIGINT         NOT NULL REFERENCES bolsita (id),
    entidad           VARCHAR(80)    NOT NULL,
    instrumento       VARCHAR(20)    NOT NULL,
    monto             NUMERIC(19, 4) NOT NULL,
    tasa              NUMERIC(9, 6)  NOT NULL,
    fecha_inicio      DATE           NOT NULL,
    fecha_vencimiento DATE           NOT NULL,
    estado            VARCHAR(10)    NOT NULL,
    monto_cobrado     NUMERIC(19, 4)
);

CREATE TABLE plan_inversion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil          VARCHAR(20)    NOT NULL,
    objetivo_bajo   INTEGER        NOT NULL,
    objetivo_medio  INTEGER        NOT NULL,
    objetivo_alto   INTEGER        NOT NULL,
    aporte_mensual  NUMERIC(19, 4)
);
