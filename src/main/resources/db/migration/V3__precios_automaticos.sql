-- Etapa 2: precios automáticos y dólar CCL.

-- Variación del día que informa la fuente (fracción: -0.0123 = -1,23%). Vacía en precios manuales.
ALTER TABLE precio ADD COLUMN variacion_diaria NUMERIC(9, 6);

CREATE TABLE dolar_ccl (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TIMESTAMP      NOT NULL,
    compra     NUMERIC(19, 4) NOT NULL,
    venta      NUMERIC(19, 4) NOT NULL
);
CREATE INDEX idx_dolar_ccl_fecha ON dolar_ccl (fecha_hora);
